/// Compile Rust source to JS. Returns JSON: `{ code, sourceMap, diagnostics }`; `code` and
/// `sourceMap` are null when there are errors.
///
/// `resolver(path)` returns the text of another file (for `mod name;`, which reads `name.rs` next
/// to `filename`), or null/undefined when there's no such file.
#[wasm_bindgen(js_name = compileJson)]
pub fn compile_json(source: &str, filename: &str, resolver: Option<js_sys::Function>) -> String {
    let resolve = |path: &str| -> Option<String> {
        let f = resolver.as_ref()?;
        f.call1(&JsValue::NULL, &JsValue::from_str(path))
            .ok()?
            .as_string()
    };
    serde_json::to_string(&compile_with(source, filename, &resolve)).unwrap()
}

/// Install typed bindings for `NS` (Rust declarations generated by `tools/dts2rs.mjs`). Returns
/// a JSON array of problems found; compiles use the bindings from then on.
#[wasm_bindgen(js_name = setNsBindings)]
pub fn set_ns_bindings(text: &str) -> String {
    serde_json::to_string(&bindings::set(text)).unwrap()
}

/// Native counterpart of `setNsBindings`.
pub fn set_bindings(text: &str) -> Vec<String> {
    bindings::set(text)
}

